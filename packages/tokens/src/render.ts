import { colorRoles, motion, palettes, radius, space, touch, type, type Palette } from './tokens';

const kebab = (s: string) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

function paletteVars(p: Palette, indent: string): string {
  return colorRoles.map((role) => `${indent}--color-${kebab(role)}: ${p[role]};`).join('\n');
}

function staticVars(indent: string): string {
  const lines: string[] = [];
  lines.push(`${indent}--font-family: ${type.fontFamily};`);
  for (const [k, v] of Object.entries(type.size)) lines.push(`${indent}--text-${k}: ${v}px;`);
  for (const [k, v] of Object.entries(type.weight)) lines.push(`${indent}--weight-${k}: ${v};`);
  for (const [k, v] of Object.entries(radius)) lines.push(`${indent}--radius-${k}: ${v}px;`);
  for (const [k, v] of Object.entries(space)) lines.push(`${indent}--space-${k}: ${v}px;`);
  for (const [k, v] of Object.entries(touch)) lines.push(`${indent}--touch-${kebab(k)}: ${v}px;`);
  for (const [k, v] of Object.entries(motion)) {
    if (typeof v === 'number') continue;
    lines.push(`${indent}--motion-${kebab(k)}-duration: ${v.durationMs}ms;`);
    lines.push(`${indent}--motion-${kebab(k)}-easing: ${v.easing};`);
  }
  return lines.join('\n');
}

function reducedMotionVars(indent: string): string {
  return Object.entries(motion)
    .filter(([, v]) => typeof v !== 'number')
    .map(([k, v]) => {
      const ms = Math.min((v as { durationMs: number }).durationMs, motion.reducedMaxMs);
      // Ambient loops (SOS pulse, live dot) stop entirely.
      return `${indent}--motion-${kebab(k)}-duration: ${k === 'ambient' ? 0 : ms}ms;`;
    })
    .join('\n');
}

/**
 * Dark is the default (dark-first product). `data-theme` on <html> pins a
 * choice; without it the OS preference wins. `data-motion="reduced"` mirrors
 * the in-app Reduce motion switch.
 */
export function renderCss(): string {
  return `/* Generated by @erp/tokens — do not edit by hand. */
:root {
${staticVars('  ')}
}

:root,
:root[data-theme="dark"] {
  color-scheme: dark;
${paletteVars(palettes.dark, '  ')}
}

@media (prefers-color-scheme: light) {
  :root:not([data-theme="dark"]) {
    color-scheme: light;
${paletteVars(palettes.light, '    ')}
  }
}

:root[data-theme="light"] {
  color-scheme: light;
${paletteVars(palettes.light, '  ')}
}

@media (prefers-reduced-motion: reduce) {
  :root:not([data-motion="full"]) {
${reducedMotionVars('    ')}
  }
}

:root[data-motion="reduced"] {
${reducedMotionVars('  ')}
}
`;
}

function dartColor(value: string): string {
  const hex = /^#([0-9a-f]{6})$/i.exec(value);
  if (hex?.[1]) return `Color(0xFF${hex[1].toUpperCase()})`;
  const rgba = /^rgba\((\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\)$/.exec(value);
  if (rgba) {
    const [r, g, b, a] = rgba.slice(1).map(Number) as [number, number, number, number];
    const h = (n: number) => n.toString(16).padStart(2, '0').toUpperCase();
    return `Color(0x${h(Math.round(a * 255))}${h(r)}${h(g)}${h(b)})`;
  }
  throw new Error(`Unsupported colour ${value}`);
}

/** Flutter mirror of the same tokens (Components doc: one library, two platforms). */
export function renderDart(): string {
  const cls = (name: string, p: Palette) =>
    `class ${name} {\n  const ${name}._();\n${colorRoles
      .map((r) => `  static const Color ${r} = ${dartColor(p[r])};`)
      .join('\n')}\n}`;
  const motionLines = Object.entries(motion)
    .filter(([, v]) => typeof v !== 'number')
    .map(([k, v]) => `  static const Duration ${k} = Duration(milliseconds: ${(v as { durationMs: number }).durationMs});`)
    .join('\n');
  return `// Generated by @erp/tokens — do not edit by hand.
import 'package:flutter/painting.dart';

${cls('ErpDarkColors', palettes.dark)}

${cls('ErpLightColors', palettes.light)}

class ErpMotion {
  const ErpMotion._();
${motionLines}
  static const Duration reducedMax = Duration(milliseconds: ${motion.reducedMaxMs});
}
`;
}
